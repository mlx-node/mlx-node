/** `template` with every `{name}` replaced by `values[name]`; a name with no value stays as written. */
export function fill(template: string, values: Readonly<Record<string, string | number>>): string {
  let out = '';
  let i = 0;
  while (i < template.length) {
    const open = template.indexOf('{', i);
    if (open === -1) break;
    const close = template.indexOf('}', open + 1);
    if (close === -1) break;
    const name = template.slice(open + 1, close);
    const value = values[name];
    out += template.slice(i, open) + (value === undefined ? template.slice(open, close + 1) : String(value));
    i = close + 1;
  }
  return out + template.slice(i);
}
