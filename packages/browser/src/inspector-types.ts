//
// The worker (`mlx-worker.ts`) and the main-thread bridge
// (`demo/lib/inspector-client.ts`) both need to write/read these `type` fields
// on `postMessage` payloads. Exporting them here keeps the single source of
// truth in this file so the two ends can't drift on a typo. The TypeScript
// literal unions above (`type: 'runForInspector'` etc.) are intentionally kept
// as plain string literals for readability; the constants are the *runtime*
// values both sides use.

export const INSPECTOR_REQUEST_TYPE = 'runForInspector' as const;
export const INSPECTOR_RESULT_TYPE = 'inspectorResult' as const;
export const INSPECTOR_ERROR_TYPE = 'inspectorError' as const;

// -----------------------------------------------------------------------------
// Tokenize worker bridge (chapter 1 — Tokenization).
// -----------------------------------------------------------------------------
//
// The Tokenization chapter shows the live Qwen3 tokenizer slicing arbitrary
// strings into BPE sub-words. It needs only the token list (no attention
// scores, no generation), so we expose a thin worker message that returns a
// `TokenInfo[]`. The worker's implementation currently reuses the loaded
// `model.runForInspector` path with `attention: false, maxNewTokens: 1` to
// reach the tokenizer — the only access point exposed to JS without a Rust
// change — and discards the generated token. If we later add a tokenizer-only
// NAPI method the worker handler can switch over transparently.

export type TokenizeRequest = {
  type: 'tokenize';
  /** Caller-supplied correlation id. The worker echoes this in the response. */
  id: string;
  /** Raw string to tokenize. The tokenizer runs without the chat template — this
   *  is a "what does the model see for this exact string?" hook. */
  prompt: string;
};

export type TokenizeResult =
  | { type: 'tokenizeResult'; id: string; tokens: TokenInfo[] }
  | { type: 'tokenizeError'; id: string; error: string };

export const TOKENIZE_REQUEST_TYPE = 'tokenize' as const;
export const TOKENIZE_RESULT_TYPE = 'tokenizeResult' as const;
export const TOKENIZE_ERROR_TYPE = 'tokenizeError' as const;

// -----------------------------------------------------------------------------
// Embed worker bridge (chapter 2 — Embeddings).
// -----------------------------------------------------------------------------
//
// The Embeddings chapter projects the model's embedding matrix to 2D with PCA.
// It tokenizes a curated word list (via the existing `tokenize` message) and
// then needs the per-token embedding vector — `[N, hidden_dim]` floats. The
// worker handler calls the NAPI method `model.embedTokens(tokenIds)`, which
// runs `weight.take(token_ids, axis=0)` on the model thread and returns a
// flat row-major Float32Array. The buffer is transferred for zero-copy
// postMessage.

export type EmbedRequest = {
  type: 'embed';
  /** Caller-supplied correlation id. The worker echoes this in the response. */
  id: string;
  /** Token ids to look up. Each must be in `[0, vocab)`; out-of-range values
   *  surface as an `embedError` from the backend. */
  tokenIds: number[];
};

export type EmbedResult =
  | {
      type: 'embedResult';
      id: string;
      /** Flat row-major `[tokenIds.length, hiddenDim]` embeddings. */
      embeddings: Float32Array;
      hiddenDim: number;
    }
  | { type: 'embedError'; id: string; error: string };

export const EMBED_REQUEST_TYPE = 'embed' as const;
export const EMBED_RESULT_TYPE = 'embedResult' as const;
export const EMBED_ERROR_TYPE = 'embedError' as const;

// -----------------------------------------------------------------------------
// Notes for the backend implementer (crates/mlx-core, Rust).
// -----------------------------------------------------------------------------
//
// The Rust side should expose a NAPI method on the model class (or a new
// dedicated handle) with this signature:
//
//   #[napi]
//   pub fn run_for_inspector(
//     &self,
//     prompt: String,
//     opts: InspectorRunOptions,
//   ) -> napi::Result<AttentionRunNapi>;
//
// Where:
//
//   #[napi(object)]
//   pub struct InspectorRunOptions {
//     pub attention: Option<bool>,
//     pub attention_layers: Option<Vec<i32>>,
//     pub max_new_tokens: Option<i32>,
//   }
//
//   #[napi(object)]
//   pub struct AttentionRunNapi {
//     pub prompt: String,
//     pub tokens: Vec<TokenInfoNapi>,
//     pub generated_token: TokenInfoNapi,
//     pub attention: Vec<AttentionLayerNapi>,
//     pub model_meta: ModelMetaNapi,
//   }
//
//   #[napi(object)]
//   pub struct AttentionLayerNapi {
//     pub layer_index: i32,
//     pub kind: String, // "full" | "linear"
//     pub num_heads: i32,
//     pub num_kv_heads: i32,
//     pub scores: napi::bindgen_prelude::Float32Array,
//   }
//
// NAPI-RS converts snake_case Rust field names to camelCase JS field names
// automatically; the generated index.d.cts will match the TypeScript types
// above. Verify with `yarn build` and a `tsc --noEmit` smoke check.
//
// During the forward pass in qwen3_5/attention.rs, after computing
// `softmax(QK^T / sqrt(d_head))` and BEFORE the matmul with V, if the
// inspector toggle is on, copy the score tensor (shape: [num_heads, seq_q, seq_k])
// out of GPU memory into a CPU-side Vec<f32>. This is the layout consumed
// above (row-major, head-major).
//
// Performance: this hook is off by default. With it on, expect ~1.5-2x decode
// slowdown depending on captured layer count. Document this in the lesson copy.
