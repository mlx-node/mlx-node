//! DSML tool calls: the turn's reasoning, content and tool calls from the
//! generated ids.
//!
//! The grammar is the model's own `encoding/encoding.py`
//! (`parse_message_from_completion_text`, `parse_tool_calls`; MIT, DeepSeek);
//! the leniency follows deepseek-recipe's stream parser
//! (`deepseek-recipe/src/stream/output_parser.rs`; MIT): any run of newlines
//! may precede the block, whitespace between tags is skipped, and text after
//! the closed block is dropped. Markup counts only where the model emitted
//! the `｜DSML｜` and `</think>` ids, never their plain-text spellings.
//!
//! Content and reasoning keep the generated bytes except at the reasoning
//! close: the engine's continuation check normalizes whitespace there and
//! refuses a reasoning that ends, or a content that starts, with whitespace.

use napi::Result;
use serde_json::{Map, Value};

use crate::engine::backend::FinalizeArgs;
use crate::engine::finalize::finalize_chat_result_with;
use crate::engine::types::ChatResult;
use crate::tokenizer::Qwen3Tokenizer;
use crate::tools::ToolCallResult;

pub(crate) const DSML: &str = "｜DSML｜";

fn is_ws(c: char) -> bool {
    c.is_ascii_whitespace()
}

fn decode(tok: &Qwen3Tokenizer, ids: &[u32]) -> String {
    tok.decode_sync(ids, true).unwrap_or_else(|e| {
        tracing::warn!("deepseek_v41: decode generated ids: {e}");
        String::new()
    })
}

/// `ids` decoded with every `dsml` id spelled as one char absent from the
/// rest of the text, so only emitted markers can match a tag.
struct Marked {
    text: String,
    mark: char,
}

impl Marked {
    fn new(tok: &Qwen3Tokenizer, ids: &[u32], dsml: Option<u32>) -> Self {
        let parts: Vec<String> = match dsml {
            Some(d) => ids.split(|&t| t == d).map(|s| decode(tok, s)).collect(),
            None => vec![decode(tok, ids)],
        };
        let mark = ('\u{E000}'..='\u{F8FF}')
            .find(|c| parts.iter().all(|p| !p.contains(*c)))
            .unwrap_or('\u{F8FF}');
        Self {
            text: parts.join(mark.encode_utf8(&mut [0; 4])),
            mark,
        }
    }

    fn tag(&self, s: &str) -> String {
        s.replace(DSML, self.mark.encode_utf8(&mut [0; 4]))
    }

    fn restore(&self, s: &str) -> String {
        s.replace(self.mark, DSML)
    }
}

/// `(text, tool_calls, thinking)` of one turn.
pub(crate) fn parse_turn(
    tok: &Qwen3Tokenizer,
    ids: &[u32],
    thinking_enabled: bool,
    think_end_id: Option<u32>,
    dsml_id: Option<u32>,
    include_reasoning: bool,
) -> (String, Vec<ToolCallResult>, Option<String>) {
    let close = think_end_id.and_then(|t| ids.iter().position(|&x| x == t));
    let (reasoning, content) = match close {
        Some(k) if thinking_enabled => (Some(&ids[..k]), &ids[k + 1..]),
        // no close before the end: the whole turn is reasoning
        None if thinking_enabled && think_end_id.is_some() => (Some(ids), &ids[..0]),
        _ => (None, ids),
    };
    let thinking = reasoning
        .map(|r| decode(tok, r).trim_end_matches(is_ws).to_string())
        .filter(|t| !t.is_empty());
    if reasoning.is_some() && close.is_none() {
        let thinking = thinking.filter(|_| include_reasoning);
        return (String::new(), Vec::new(), thinking);
    }
    let m = Marked::new(tok, content, dsml_id);
    let (mut text, calls) = parse_content(&m);
    if thinking.is_some() {
        text = text.trim_start_matches(is_ws).to_string();
    }
    (text, calls, thinking.filter(|_| include_reasoning))
}

/// Content before the first `\n*<｜DSML｜ calls>` and the block's calls. An
/// unclosed block (length stop) parses to no call and stays in the text.
fn parse_content(m: &Marked) -> (String, Vec<ToolCallResult>) {
    let open = m.tag("<｜DSML｜ calls>");
    let close = m.tag("</｜DSML｜ calls>");
    let Some(at) = m.text.find(&open) else {
        return (m.restore(&m.text), Vec::new());
    };
    let body = at + open.len();
    let Some(len) = m.text[body..].find(&close) else {
        return (m.restore(&m.text), Vec::new());
    };
    let raw = m.restore(&m.text[at..body + len + close.len()]);
    let pre = m.text[..at].trim_end_matches('\n');
    (
        m.restore(pre),
        parse_block(m, &m.text[body..body + len], raw),
    )
}

/// The invokes of one closed block. Malformed markup fails the whole block
/// (one `parse_error`, as `encoding.py` raises); a duplicate parameter or a
/// `string="false"` value that is not JSON fails only its invoke.
fn parse_block(m: &Marked, body: &str, raw: String) -> Vec<ToolCallResult> {
    match parse_invokes(m, body) {
        Ok(calls) => calls,
        Err(e) => vec![ToolCallResult::parse_error(
            String::new(),
            raw.clone(),
            format!("DSML tool calls: {e}"),
            raw,
        )],
    }
}

fn parse_invokes(m: &Marked, body: &str) -> std::result::Result<Vec<ToolCallResult>, String> {
    let inv_open = m.tag("<｜DSML｜ invoke name=\"");
    let inv_close = m.tag("</｜DSML｜ invoke>");
    let par_open = m.tag("<｜DSML｜ parameter name=\"");
    let par_close = m.tag("</｜DSML｜ parameter>");
    let mut calls = Vec::new();
    let mut rest = body.trim_start_matches(is_ws);
    while !rest.is_empty() {
        let start = rest;
        let r = rest
            .strip_prefix(&inv_open)
            .ok_or_else(|| format!("expected an invoke at {:?}", m.restore(head(rest))))?;
        let (name, mut r) = r
            .split_once("\">")
            .ok_or_else(|| "unterminated invoke name".to_string())?;
        let mut args = Map::new();
        let mut fail: Option<(&str, String)> = None;
        loop {
            r = r.trim_start_matches(is_ws);
            if let Some(after) = r.strip_prefix(&inv_close) {
                r = after;
                break;
            }
            let p = r
                .strip_prefix(&par_open)
                .ok_or_else(|| format!("expected a parameter at {:?}", m.restore(head(r))))?;
            let (key, p) = p
                .split_once("\" string=\"")
                .ok_or_else(|| "parameter without a string attribute".to_string())?;
            let (is_str, p) = if let Some(p) = p.strip_prefix("true\">") {
                (true, p)
            } else if let Some(p) = p.strip_prefix("false\">") {
                (false, p)
            } else {
                return Err(format!("parameter {key:?}: string must be true or false"));
            };
            let (val, p) = p
                .split_once(&par_close)
                .ok_or_else(|| format!("parameter {key:?} is not closed"))?;
            r = p;
            let key = m.restore(key);
            let val = m.restore(val);
            if args.contains_key(&key) {
                fail.get_or_insert(("parse_error", format!("duplicate parameter {key:?}")));
                continue;
            }
            let value = if is_str {
                Value::String(val)
            } else {
                match serde_json::from_str(&val) {
                    Ok(v) => v,
                    Err(e) => {
                        fail.get_or_insert(("invalid_json", format!("parameter {key:?}: {e}")));
                        continue;
                    }
                }
            };
            args.insert(key, value);
        }
        let name = m.restore(name);
        let raw = m.restore(&start[..start.len() - r.len()]);
        calls.push(match fail {
            None => ToolCallResult::ok(name, Value::Object(args), raw),
            Some(("invalid_json", e)) => ToolCallResult::invalid_json(name, e, raw),
            Some((_, e)) => ToolCallResult::parse_error(name, raw.clone(), e, raw),
        });
        rest = r.trim_start_matches(is_ws);
    }
    Ok(calls)
}

fn head(s: &str) -> &str {
    let end = s.char_indices().nth(40).map_or(s.len(), |(i, _)| i);
    &s[..end]
}

/// The generated text after the reasoning close (`raw_text` without the
/// reasoning), cut at the close id.
fn public_raw(args: &FinalizeArgs<'_>, text: &str) -> String {
    if !args.thinking_enabled {
        return text.to_string();
    }
    let close = args
        .think_end_id
        .and_then(|t| args.generated_tokens.iter().position(|&x| x == t));
    match close {
        Some(k) => decode(args.tokenizer, &args.generated_tokens[k + 1..]),
        None if args.think_end_id.is_some() => String::new(),
        None => text.to_string(),
    }
}

pub(crate) fn finalize(args: FinalizeArgs<'_>, dsml_id: Option<u32>) -> Result<ChatResult> {
    finalize_chat_result_with(
        args,
        |_, a| {
            parse_turn(
                a.tokenizer,
                a.generated_tokens,
                a.thinking_enabled,
                a.think_end_id,
                dsml_id,
                a.include_reasoning,
            )
        },
        |text, a| public_raw(a, text),
    )
}

